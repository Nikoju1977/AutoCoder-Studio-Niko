import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {chromium} from 'playwright';
const base=process.env.AUTOCODER_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const context=await browser.newContext({acceptDownloads:true,serviceWorkers:'block',viewport:{width:390,height:844}});
 const page=await context.newPage();const errors=[],roles=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.route('**/api/generate',async route=>{
   const body=route.request().postDataJSON();roles.push(body.role);
   if(body.prompt.startsWith('Sélectionne zéro'))return route.fulfill({json:{files:[{name:'tools.json',content:'{"tools":["project.audit"]}'}]}});
   const file=body.role==='architect'?{name:'plan.md',content:'Corriger JSON'}:body.role==='developer'?{name:'config.json',content:'{"ok":true}'}:{name:'review.json',content:'{"accept":true,"issues":[]}'};
   await route.fulfill({json:{files:[file],plan:[],notes:''}});
 });
 await page.goto(base+'/code-mode-x.html');
 await page.locator('#project-file').setInputFiles({name:'projet.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({projectName:'test',files:{'config.json':'{'}}))});
 await page.waitForFunction(()=>!document.querySelector('#audit').disabled);
 await page.locator('#audit').click();assert.match(await page.locator('#journal').innerText(),/JSON_INVALID/);
 await page.locator('#evolution-plan').click();assert.match(await page.locator('#evolution-report').innerText(),/JSON_INVALID/);
 await page.locator('#evolution-prepare').click();assert.match(await page.locator('#prompt').inputValue(),/JSON/);
 await page.locator('#memory-note').fill('Corriger JSON');
 await page.locator('#memory-save').click();assert.match(await page.locator('#memory-list').innerText(),/Corriger JSON/);
 await page.locator('#attempt-budget').selectOption('1');
 await page.locator('#token').fill('test-token-with-at-least-32-characters');
 await page.locator('#run').click();assert.equal(roles.length,0);
 await page.locator('#consent').check();
 await page.locator('#run').click();await page.waitForFunction(()=>!document.querySelector('#export').disabled);
 assert.deepEqual(roles,['architect','developer','critic']);
 assert.equal(await page.locator('#before').inputValue(),'{');
 assert.equal(await page.locator('#after').inputValue(),'{"ok":true}');
 assert.equal(await page.locator('#token').inputValue(),'');
 const pending=page.waitForEvent('download');await page.locator('#export').click();const download=await pending;
 const output=JSON.parse(readFileSync(await download.path(),'utf8'));
 assert.equal(output.files['config.json'],'{"ok":true}');
 assert.equal(await page.locator('#source').inputValue(),'{');
 assert.ok(await page.evaluate(()=>document.body.scrollWidth<=innerWidth+1),'Mobile overflow');
 await page.route('https://api.github.com/users/Nikoju1977/repos?**',route=>route.fulfill({json:[{full_name:'Nikoju1977/Audio',private:false,archived:false,default_branch:'main',description:'Synthé'}],headers:{'Access-Control-Allow-Origin':'*'}}));
 await page.locator('#catalog-load').click();
 await page.waitForFunction(()=>document.querySelector('#catalog-info').textContent.includes('Nikoju1977/Audio')&&!document.querySelector('#catalog-open').disabled);
 assert.match(await page.locator('#catalog-info').innerText(),/Nikoju1977\/Audio/);
 await page.locator('#catalog-query').fill('absent');
 assert.equal(await page.locator('#catalog-open').isDisabled(),true);
 await page.locator('#catalog-query').fill('Audio');
 assert.equal(await page.locator('#catalog-select').inputValue(),'Nikoju1977/Audio');
 assert.equal(await page.locator('#catalog-open').isDisabled(),false);
 await page.locator('#native-auto').check();
 await page.locator('#token').fill('test-token-with-at-least-32-characters');
 await page.locator('#consent').check();
 await page.locator('#run').click();
 await page.waitForFunction(()=>!document.querySelector('#export').disabled);
 assert.deepEqual(roles.slice(3),['architect','architect','developer','critic']);
 assert.match(await page.locator('#native-result').innerText(),/project.audit/);
 await page.locator('#classical-plan').click();
 assert.match(await page.locator('#classical-result').innerText(),/criticalPathEstimate/);
 await page.locator('#classical-run').click();
 await page.waitForFunction(()=>document.querySelector('#classical-result').textContent.includes('classical_local'));
 assert.match(await page.locator('#classical-result').innerText(),/JSON_INVALID/);
 await page.locator('#classical-optimize').click();
 assert.match(await page.locator('#classical-opt-result').innerText(),/"totalValue": 9/);
 await page.locator('#hybrid-run').click();
 await page.waitForFunction(()=>document.querySelector('#hybrid-result').textContent.includes('completed_local'));
 assert.match(await page.locator('#hybrid-result').innerText(),/JSON_INVALID/);
 await page.locator('#hybrid-kind').selectOption('develop');
 await page.locator('#hybrid-prompt').fill('Corriger JSON');
 await page.locator('#hybrid-local').uncheck();
 const beforeHybridCalls=roles.length;
 await page.locator('#hybrid-run').click();
 await page.waitForFunction(()=>!document.querySelector('#hybrid-handoff').disabled);
 await page.locator('#hybrid-handoff').click();
 assert.match(await page.locator('#prompt').inputValue(),/Précontrôle local/);
 assert.equal(await page.locator('#consent').isChecked(),false);
 assert.equal(roles.length,beforeHybridCalls);
 assert.deepEqual(errors,[]);
 console.log('PASS Code Mode X: local audit, roadmap, memory, consent, mocked agent flow, export, mobile layout');
}finally{await browser.close();}
